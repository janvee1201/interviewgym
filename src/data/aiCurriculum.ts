// Helper to look up any topic by title or ID across all sections
export function findTopic(titleOrId: string): CurriculumTopic | undefined {
  const query = titleOrId.toLowerCase().trim();
  for (const section of AI_CURRICULUM_SECTIONS) {
    for (const topic of section.topics) {
      if (
        topic.id.toLowerCase() === query ||
        topic.title.toLowerCase() === query ||
        topic.title.toLowerCase().includes(query)
      ) {
        return topic;
      }
    }
  }
  return undefined;
}

// Helper to search topics with rich section path resolution
export function searchCurriculum(query: string): Array<{ topic: CurriculumTopic; section: CurriculumSection }> {
  const clean = query.toLowerCase().trim();
  if (!clean) return [];

  const results: Array<{ topic: CurriculumTopic; section: CurriculumSection }> = [];

  for (const section of AI_CURRICULUM_SECTIONS) {
    for (const topic of section.topics) {
      const matchTitle = topic.title.toLowerCase().includes(clean);
      const matchOneLiner = topic.oneLiner.toLowerCase().includes(clean);
      const matchSubgroup = topic.subgroup.toLowerCase().includes(clean);
      const matchSection = section.title.toLowerCase().includes(clean);

      if (matchTitle || matchOneLiner || matchSubgroup || matchSection) {
        results.push({ topic, section });
      }
    }
  }

  return results;
}
